const fs = require('fs')
const path = require('path')
const assert = require('assert/strict')

const pluginDir = __dirname
const pluginPath = path.join(pluginDir, 'desktop', 'plugin.js')
const readmePath = path.join(pluginDir, '..', 'README.md')
const jumpPath = path.join(pluginDir, '..', 'install', 'overlook.html')
const readme = fs.readFileSync(readmePath, 'utf8')
const plugin = fs.readFileSync(pluginPath, 'utf8')
const jump = fs.readFileSync(jumpPath, 'utf8')

assert.equal(path.basename(pluginDir), 'overlook', 'install probe uses the last subdir as the desktop-plugins folder name')
assert.ok(fs.existsSync(pluginPath), 'installer copies overlook/desktop/ so only plugin.js lands on disk')
assert.equal(fs.existsSync(path.join(pluginDir, 'plugin.js')), false, 'a root plugin.js would make the installer copy the test files too')
assert.deepEqual(fs.readdirSync(path.join(pluginDir, 'desktop')), ['plugin.js'], 'the copied desktop tree must contain only plugin.js')

assert.match(readme, /https:\/\/hermes-agent\.nousresearch\.com\/docs\/zh-Hans\/developer-guide\/desktop-plugin-sdk#install-link/, 'README must cite the Desktop Plugin SDK install-link section')
assert.match(readme, /https:\/\/raw\.githack\.com\/glwlg\/Hermes-plugins\/main\/install\/overlook\.html/, 'README must ship a GitHub-clickable HTTPS jump page')
assert.match(readme, /https:\/\/raw\.githack\.com\/glwlg\/Hermes-plugins\/main\/install\/overlook\.html\?force=1/, 'README must ship a force-replace jump page')
assert.match(readme, /hermes:\/\/plugin\/install\?repo=glwlg\/Hermes-plugins\/overlook/, 'README still documents the raw hermes:// URL for the address bar')
assert.match(readme, /hermes:\/\/plugin\/install\?repo=glwlg\/Hermes-plugins\/overlook&force=1/, 'README still documents the force hermes:// URL')
assert.doesNotMatch(readme, /Install from Git/, 'Desktop has no Settings → Plugins → Install from Git path for this plugin')
assert.doesNotMatch(readme, /hermes:\/\/plugin\/install\?[^\\s)]*enable=1/, 'enable=1 is an agent allow-list flag; Overlook is desktop-only')
assert.doesNotMatch(readme, /hermes:\/\/plugin\/install\?repo=glwlg\/Hermes-plugins(?:["'\\s)]|&|$)/, 'a repo-root install link cannot see overlook/desktop/plugin.js')
assert.match(plugin, /id: ID/, 'installed plugin.js must keep the stable Overlook id')
assert.match(plugin, /const ID = 'overlook'/)
assert.match(jump, /hermes:\/\/plugin\/install\?repo=glwlg\/Hermes-plugins\/overlook/, 'jump page must open the exact install identifier')
assert.match(jump, /force=1/, 'jump page must support replacing an existing copy')

console.log('overlook install link contract passed')
